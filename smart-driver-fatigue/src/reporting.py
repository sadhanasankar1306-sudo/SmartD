"""
Trip Safety Reporting module for generating structured safety summaries and CSV exports.
"""
import csv
import io
import time
from typing import Any, Dict, List, Optional


def generate_trip_summary(session_data: Dict[str, Any], events: List[Dict[str, Any]]) -> str:
    """
    Generate a formatted text safety report for a driver monitoring session.
    """
    duration_min = round(session_data.get("duration_s", 0.0) / 60.0, 1)
    cautions = session_data.get("total_cautions", 0)
    high_warnings = session_data.get("total_high_warnings", 0)
    peak_risk = session_data.get("peak_risk", 0.0)
    avg_risk = session_data.get("avg_risk", 0.0)
    
    start_str = time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(session_data.get("start_time", time.time())))
    end_str = time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(session_data.get("end_time", time.time()))) if session_data.get("end_time") else "In Progress"

    lines = [
        "=" * 60,
        "SMART DRIVER FATIGUE PREVENTION SYSTEM - TRIP SAFETY REPORT",
        "=" * 60,
        f"Session ID:         {session_data.get('id', 'N/A')}",
        f"Start Time:         {start_str}",
        f"End Time:           {end_str}",
        f"Trip Duration:      {duration_min} minutes",
        "-" * 60,
        "FATIGUE RISK METRICS (Heuristic Scale 0-100):",
        f"  Peak Risk Score:  {peak_risk:.1f}/100",
        f"  Average Risk:     {avg_risk:.1f}/100",
        f"  Caution Events:   {cautions}",
        f"  High Warnings:    {high_warnings}",
        "-" * 60,
        "SAFETY EVALUATION & RECOMMENDATIONS:",
    ]

    if high_warnings > 0 or peak_risk >= 70.0:
        lines.extend([
            "  STATUS: HIGH FATIGUE RISK DETECTED",
            "  - Prolonged eye closures or severe drowsiness indicators were logged.",
            "  - ADVISORY: Driver should immediately pull over in a safe parking zone,",
            "    take a 20-minute restorative nap, and hydrate before resuming travel.",
        ])
    elif cautions > 1 or peak_risk >= 40.0:
        lines.extend([
            "  STATUS: MODERATE FATIGUE SIGNS OBSERVED",
            "  - Repetitive yawning, slow blinks, or posture shifts recorded.",
            "  - ADVISORY: Plan a rest break within the next 15-30 minutes.",
            "    Ensure adequate cabin ventilation and fresh air circulation.",
        ])
    else:
        lines.extend([
            "  STATUS: NOMINAL / LOW RISK PROFILE",
            "  - No persistent micro-sleep or severe fatigue events detected.",
            "  - REMINDER: Routine 15-minute breaks every 2 hours are recommended",
            "    regardless of perceived alertness.",
        ])

    lines.extend([
        "-" * 60,
        f"DETAILED EVENT LOG ({len(events)} events):"
    ])
    
    if not events:
        lines.append("  No warning events occurred during this session.")
    else:
        for idx, ev in enumerate(events, 1):
            t_str = time.strftime('%H:%M:%S', time.localtime(ev.get("timestamp", time.time())))
            lvl = "HIGH" if ev.get("alert_level") == 2 else "CAUTION"
            lines.append(f"  [{idx:02d}] {t_str} | {lvl:<7} | {ev.get('trigger_type', 'N/A')} - {ev.get('description', '')}")

    lines.extend([
        "=" * 60,
        "DISCLAIMER: This report is generated by an experimental research prototype.",
        "It does not guarantee accident prevention and is not a certified medical tool.",
        "=" * 60
    ])

    return "\n".join(lines)


def export_events_to_csv(events: List[Dict[str, Any]]) -> str:
    """
    Export events list to CSV string.
    """
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Event ID", "Session ID", "Timestamp", "Formatted Time", "Alert Level", "Trigger Type", "Description", "Risk Score"])
    
    for ev in events:
        t_val = ev.get("timestamp", 0.0)
        formatted_t = time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(t_val)) if t_val else ""
        writer.writerow([
            ev.get("id", ""),
            ev.get("session_id", ""),
            f"{t_val:.3f}",
            formatted_t,
            ev.get("alert_level", ""),
            ev.get("trigger_type", ""),
            ev.get("description", ""),
            ev.get("risk_score", "")
        ])
        
    return output.getvalue()
